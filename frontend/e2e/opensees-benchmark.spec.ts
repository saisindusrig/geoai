import { test, expect } from "@playwright/test";
import { readFileSync, writeFileSync } from "node:fs";

const projectId = process.env.OPENSEES_TEST_PROJECT_ID;
test.skip(!projectId, "Use a separate local solver verification project.");

test("actual solver, unit conversion, input/model staleness, undo/redo, save/reload and immutable history", async ({page,request}) => {
  test.slow();
  const errors: string[]=[];page.on("pageerror",e=>errors.push(e.message));
  await page.setViewportSize({width:1626,height:982});
  await page.route("**/api/geocode/map-runtime-config",r=>r.fulfill({json:{cesium_ion_token:null,google_maps_api_key:null}}));
  await page.goto(`/projects/${projectId}/workspace`);
  await page.getByRole("tab",{name:"Inspect",exact:true}).click();
  await page.getByRole("button",{name:"Frame assembly",exact:true}).click();
  await expect.poll(async()=>Object.keys(JSON.parse(await page.locator(".cesium-widget canvas").getAttribute("data-component-pick-points")||"{}")).length).toBe(45);
  await page.getByRole("tab",{name:"Checks",exact:true}).click();
  const panel=page.getByLabel("OpenSees axial benchmark");
  const run=async()=>{
    const pending=page.waitForResponse(r=>r.request().method()==="POST" && r.url().endsWith("/engineering/opensees"));
    await panel.getByRole("button",{name:"Run OpenSees benchmark",exact:true}).click();
    expect((await pending).ok()).toBeTruthy();
    await expect(panel.getByRole("button",{name:"Run OpenSees benchmark",exact:true})).toBeEnabled({timeout:30000});
  };
  await expect(panel.getByRole("button",{name:"Run OpenSees benchmark",exact:true})).toBeEnabled();
  await panel.getByLabel("OpenSees units").selectOption("SI");await panel.getByLabel("OpenSees load").selectOption("1");await panel.getByLabel("OpenSees elements").selectOption("1");
  await run();
  await expect(panel.getByRole("status")).toHaveText("VERIFIED · numerical benchmark only");
  await expect(panel.getByLabel("Computed OpenSees results")).toContainText("1.15000 mm");
  await expect(panel.getByLabel("Computed OpenSees results")).toContainText("100.00000 kN");
  await expect(panel).toContainText("6 actual solver cases");
  await expect(panel).toContainText("Engineering approval DISABLED");
  await expect(panel.getByLabel("Computed axial displacement diagram")).toBeVisible();
  await page.screenshot({path:"../docs/engineering-analysis/screenshots/opensees-si.png"});
  await panel.getByLabel("OpenSees elements").selectOption("4");
  await expect(panel.getByRole("status")).toContainText("STALE");
  await panel.getByLabel("OpenSees elements").selectOption("1");
  await expect(panel.getByRole("status")).not.toContainText("STALE");
  await panel.getByLabel("OpenSees units").selectOption("N-mm");
  await panel.getByLabel("OpenSees load").selectOption("2");
  await run();
  await expect(panel.getByRole("status")).toHaveText("VERIFIED · numerical benchmark only");
  await expect(panel.getByLabel("Computed OpenSees results")).toContainText("2.30000 mm");
  await panel.locator("summary").click();
  const downloadPromise=page.waitForEvent("download");await panel.getByRole("button",{name:"model.tcl",exact:true}).click();
  const downloaded=await downloadPromise;
  const text=readFileSync((await downloaded.path())!,"utf8");
  expect(text).toContain("# Units: N-mm");expect(text).toContain("uniaxialMaterial Elastic 1 200000");
  await page.reload();await page.getByRole("tab",{name:"Checks",exact:true}).click();
  await expect(panel.getByRole("status")).toHaveText("VERIFIED · numerical benchmark only");
  await expect(panel.getByLabel("OpenSees units")).toHaveValue("N-mm");
  const before=(await request.get(`http://127.0.0.1:8001/api/projects/${projectId}/engineering/opensees`));expect(before.ok()).toBeTruthy();
  const initial=(await before.json()).analyses[0];
  const scenarios=await (await request.get(`http://127.0.0.1:8001/api/projects/${projectId}/scenarios`)).json();
  const scenarioId=(Array.isArray(scenarios) ? scenarios : scenarios.scenarios)[0].scenario_id;
  const oldResponse=await request.get(`http://127.0.0.1:8001/api/projects/${projectId}/scenarios/${scenarioId}/model-revisions/latest`);expect(oldResponse.ok()).toBeTruthy();
  const old=await oldResponse.json();expect(old.id).toBeGreaterThan(0);
  await page.getByRole("tab",{name:"Inspect",exact:true}).click();
  const width=page.getByLabel("Platform width · m",{exact:true});const originalWidth=await width.inputValue();
  await width.fill(String(Number(originalWidth)+.2));await page.getByRole("button",{name:"Preview platform",exact:true}).click();
  await page.getByRole("tab",{name:"Checks",exact:true}).click();
  await expect(panel.getByRole("status")).toContainText("STALE");
  await expect(panel.getByRole("button",{name:"Run OpenSees benchmark",exact:true})).toBeDisabled();
  await page.getByRole("tab",{name:"Inspect",exact:true}).click();await page.getByRole("button",{name:"Apply platform",exact:true}).click();
  await page.getByRole("button",{name:"Undo",exact:true}).click();await expect(width).toHaveValue(originalWidth);
  await page.getByRole("button",{name:"Redo",exact:true}).click();await expect(width).toHaveValue(String(Number(originalWidth)+.2));
  const savedResponse=page.waitForResponse(r=>r.request().method()==="POST" && r.url().endsWith("/model-revisions"));
  await page.getByRole("button",{name:"Save 3D model revision",exact:true}).click();
  const saved=await (await savedResponse).json();expect(saved.id).not.toBe(old.id);
  await page.getByRole("tab",{name:"Checks",exact:true}).click();await expect(panel.getByRole("status")).toContainText("STALE");
  await page.screenshot({path:"../docs/engineering-analysis/screenshots/opensees-stale.png"});
  const server=await (await request.get(`http://127.0.0.1:8001/api/projects/${projectId}/engineering/opensees`)).json();expect(server.analyses[0].status).toBe("STALE");
  const originalResponse=await request.get(`http://127.0.0.1:8001/api/projects/${projectId}/scenarios/${scenarioId}/model-revisions/${old.id}`);expect(originalResponse.ok()).toBeTruthy();
  const original=await originalResponse.json();expect(original.document).toEqual(old.document);
  const invalid=await request.post(`http://127.0.0.1:8001/api/projects/${projectId}/engineering/opensees`,{data:{model_revision_id:saved.id,elements:3}});expect(invalid.status()).toBe(422);
  const obsolete=await request.post(`http://127.0.0.1:8001/api/projects/${projectId}/engineering/opensees`,{data:{model_revision_id:old.id}});expect(obsolete.status()).toBe(409);
  await panel.getByLabel("OpenSees units").selectOption("SI");await panel.getByLabel("OpenSees load").selectOption("1");
  await run();await expect(panel.getByRole("status")).toHaveText("VERIFIED · numerical benchmark only");
  await page.reload();await page.getByRole("tab",{name:"Checks",exact:true}).click();await expect(panel.getByRole("status")).toHaveText("VERIFIED · numerical benchmark only");
  await expect(panel).toContainText(`Result revision #${saved.id}`);
  const final=await (await request.get(`http://127.0.0.1:8001/api/projects/${projectId}/engineering/opensees`)).json();
  expect(final.analyses.find((a:{id:number;status:string})=>a.id===initial.id).status).toBe("STALE");
  writeFileSync("../docs/engineering-analysis/browser-evidence.json",JSON.stringify({project_id:projectId,saved_revision_id:saved.id,checks:["real solver","artifact download","input staleness","model preview staleness","undo/redo","save/reload","immutable prior revision","server stale status","invalid request 422","obsolete revision 409"],analyses:final.analyses},null,2));
  expect(errors).toEqual([]);await expect(page.locator(".cesium-widget-errorPanel")).toHaveCount(0);
});
